-- ==========================================
-- TABELA: CARGA_INDUSTRIASFOCO
-- ==========================================
CREATE TABLE CARGA_INDUSTRIASFOCO (
    SEQFORNECEDOR NUMBER NOT NULL,
    NOME_APRESENTACAO VARCHAR2(50) NOT NULL,
    FOCO VARCHAR2(3) NOT NULL,
    CONSTRAINT PK_INDUSTRIAS_FOCO PRIMARY KEY (COD_FORNECEDOR),
    CONSTRAINT CK_INDUSTRIAS_FOCO CHECK (FOCO IN ('SIM', 'NÃO'))
);

-- ==========================================
-- TABELA: INDUSTRIAS METAS
-- ==========================================
CREATE TABLE CARGA_INDUSTRIASMETAS (
    ID NUMBER GENERATED ALWAYS AS IDENTITY,
    DATA DATE NOT NULL,
    SEQFORNECEDOR NUMBER NOT NULL,
    NROREPRESENTANTE NUMBER(5) NOT NULL,
    META_POSITIVACAO NUMBER(5) NOT NULL,
    META_FATURAMENTO NUMBER(18,6) NOT NULL,
    CONSTRAINT PK_INDUSTRIAS_METAS PRIMARY KEY (ID)
);

-- ==========================================
-- INDEX: INDUSTRIAS METAS
-- ==========================================
CREATE INDEX IDX_IND_METAS_DATA
ON CARGA_INDUSTRIASMETAS (DATA);

CREATE INDEX IDX_IND_METAS_FORNECEDOR
ON CARGA_INDUSTRIASMETAS (SEQFORNECEDOR);

CREATE INDEX IDX_IND_METAS_REP
ON CARGA_INDUSTRIASMETAS (NROREPRESENTANTE);

CREATE INDEX IDX_IND_METAS_DATA_REP
ON CARGA_INDUSTRIASMETAS (DATA, NROREPRESENTANTE);
